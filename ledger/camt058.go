// ISO 20022 camt.058.001 Notification to Receive Cancellation
// Advice export (LG-404, fintech: ISO 20022 收款通知撤销建议 MX
// 导出面).
//
// This is the cancellation advice for the camt.057 notification
// (LG-403): the same pre-advice — "there will be money coming
// into my account" — withdrawn, by the same account owner to the
// same servicing bank, for the same next run of the same schedule.
// Same source (the next run of one transfer schedule, LG-41),
// same direction (To account, the beneficiary, to the servicing
// bank named by the caller), same limit (one run only). It is not
// a camt.056: that one is an FI-to-FI payment cancellation
// request; this one is an account owner telling its account bank
// to disregard a notification to receive it sent earlier.
//
// Version pinned by the spec's registry check (LG-404): the
// registry's latest camt.058 is .001.08 — the CBPR+ SR2025 usage
// guideline (Clearstream, January 2026, generated by MyStandards)
// restricts the base message camt.058.001.08, SWIFT's Standard
// Release 2025 activated it on 2025-09-22, and the deferred
// SR2026 notes keep the base message at .001.08 (only the usage
// identifier moves, swift.cbprplus.02 to .03). The registry-
// generated Go binding (UNO-SOFT/iso20022, regenerated 2026-09-06
// from the registry) still carries only camt_058_001_07: it lags
// for this one message — the same regeneration carries
// camt_056_001_10 and pacs_008_001_10, so it is not a frozen
// snapshot — and is not followed here. The structure below is
// verified against that binding's NotificationToReceive-
// CancellationAdviceV07 for the parts that did not change
// (Document > NtfctnToRcvCxlAdvc > GrpHdr (GroupHeader77: MsgId /
// CreDtTm) + OrgnlNtfctn (OriginalNotification14: OrgnlMsgId /
// OrgnlCreDtTm / OrgnlNtfctnId / NtfctnCxl / OrgnlNtfctnRef),
// stable since the V03 Message Definition Report) and against the
// Clearstream CBPR+ SR2025 guideline for the V08 addition: the
// Document is composed of four elements — Group Header, Original
// Notification, Cancellation Reason, Supplementary Data. The
// CxlRsn inner shape follows the repo's own free-form-reason
// convention (pain.011 LG-402, camt.056): Rsn/Prtry carrying the
// operator's reason verbatim, no invented reason-code table.
//
//   - Read-only: the lookup takes the read lock only (via
//     GetTransferSchedule), bumps no version, books nothing, and
//     appends no audit event. A pre-advice — and the withdrawal
//     of one — is not an attestation.
//   - OrgnlNtfctn carries only the original notification's
//     identifiers: OrgnlMsgId and OrgnlNtfctnId are both
//     "camt057-<scheduleID>-<runSeq>", the deterministic MsgId
//     LG-403 renders (its Ntfctn Id repeats its MsgId). No
//     OrgnlNtfctnRef is emitted, so no amount is restated —
//     which is what makes an FX schedule revocable here, the
//     opposite of camt.057: the advice cancels the notification
//     itself, not an amount, and an FX amount the ledger cannot
//     state is never written down.
//   - OrgnlCreDtTm is omitted on purpose: the ledger records
//     neither whether camt.057 was actually sent nor when, so the
//     original creation time is unknowable and is never guessed.
//     NtfctnCxl is likewise omitted: the advice itself is the
//     cancellation, and the indicator adds nothing.
//   - CxlRsn is emitted only when the caller gives a reason; an
//     empty reason omits the block entirely, never a defaulted
//     code (the pain.011 precedent).
//   - ServicingBIC is validated with validBIC but is not
//     embedded in the Document body: the V08 body has no
//     servicing-bank slot — the BIC names the advice's recipient
//     at the transport/header level, and the caller names it on
//     every export because the ledger holds no bank-identity
//     registry.
//   - MsgId is deterministic: "camt058-<scheduleID>-<runSeq>".
//     Repeat exports are byte-identical modulo the honest
//     wall-clock CreDtTm line (the camt.060 precedent) until a
//     run fires — then RunSeq advances and both MsgIds move with
//     it, which is a content change, not drift.
//   - The status gate is deliberately the opposite of camt.057's
//     active-only gate: only a schedule whose notification
//     premise is dead can be cancelled — paused, cancelled, or
//     completed, and an active schedule whose NextRunAt has
//     already passed its EndsAt. An active schedule with a live
//     next run reports ErrCAMT058ScheduleStillActive: the money
//     is still coming, so withdrawing the notice would mislead
//     liquidity planning. To correct a notice, pause the plan,
//     cancel the old notice, resume the plan, and re-issue.

// CAMT.058 export errors.
var (
	// ErrInvalidCAMT058Export is returned when a schedule cannot be
	// rendered as a camt.058: a servicing BIC that is not a valid
	// 8/11 BIC, or a message/original identifier outside
	// Max35Text. It is a 400-class error: the stored schedule
	// cannot be expressed as a valid cancellation advice.
	ErrInvalidCAMT058Export = errors.New("ledger: invalid camt.058 export")
	// ErrCAMT058ScheduleStillActive is returned when a camt.058 is
	// requested for a schedule whose next run is still live: an
	// active schedule whose NextRunAt has not passed its EndsAt.
	// It is a 422-class error: the schedule exists, but there is
	// still money coming, so withdrawing the notice would be a
	// false statement.
	ErrCAMT058ScheduleStillActive = errors.New("ledger: transfer schedule is still active for camt.058 cancellation advice")
)

// CAMT058ExportOptions tunes ExportCAMT058.
//
// ScheduleID names the transfer schedule whose next run's
// notification is cancelled. ServicingBIC is the BIC of the bank
// holding the account to be credited (required, 8 or 11
// characters): the advice's recipient, named by the caller on
// every export. Reason is the operator's free-form cancellation
// reason (optional): when empty, the CxlRsn block is omitted.
type CAMT058ExportOptions struct {
	ScheduleID   string
	ServicingBIC string
	Reason       string
}

// camt058MsgID derives the deterministic message ID from the
// schedule ID and the run sequence: the same run re-renders the
// same ID, and any run advance changes it.
func camt058MsgID(scheduleID string, runSeq uint64) string {
	return fmt.Sprintf("camt058-%s-%d", scheduleID, runSeq)
}

// The camt058x* structs are the export-side XML model, the
// camt057.go convention: a strict writer carrying the
// camt.058.001.08 namespace on the root and omitting every empty
// element, so the emitted document is what a bank expects to
// receive.
type camt058xDocument struct {
	XMLName            xml.Name                   `xml:"urn:iso:std:iso:20022:tech:xsd:camt.058.001.08 Document"`
	NtfctnToRcvCxlAdvc camt058xNtfctnToRcvCxlAdvc `xml:"NtfctnToRcvCxlAdvc"`
}

type camt058xNtfctnToRcvCxlAdvc struct {
	GrpHdr      camt058xGrpHdr      `xml:"GrpHdr"`
	OrgnlNtfctn camt058xOrgnlNtfctn `xml:"OrgnlNtfctn"`
	CxlRsn      *camt058xCxlRsn     `xml:"CxlRsn,omitempty"`
}

type camt058xGrpHdr struct {
	MsgID   string `xml:"MsgId"`
	CreDtTm string `xml:"CreDtTm"`
}

type camt058xOrgnlNtfctn struct {
	OrgnlMsgId    string `xml:"OrgnlMsgId"`
	OrgnlNtfctnId string `xml:"OrgnlNtfctnId"`
}

type camt058xCxlRsn struct {
	Rsn camt058xRsn `xml:"Rsn"`
}

type camt058xRsn struct {
	Prtry string `xml:"Prtry"`
}

// ExportCAMT058 renders the next run of the transfer schedule as
// an ISO 20022 camt.058.001.08 notification to receive
// cancellation advice. Unknown IDs report ErrScheduleNotFound; a
// still-active schedule with a live next run reports
// ErrCAMT058ScheduleStillActive. Only a paused, cancelled,
// completed, or exhausted schedule exports — the deliberate
// opposite of camt.057's active-only gate.
func (l *Ledger) ExportCAMT058(opts CAMT058ExportOptions) (string, error) {
	// Caller-given options fail fast, before any schedule lookup:
	// a servicing bank that is not a valid BIC can never be a
	// valid advice.
	servicing := strings.ToUpper(strings.TrimSpace(opts.ServicingBIC))
	if servicing == "" || !validBIC(servicing) {
		return "", fmt.Errorf("%w: servicing BIC %q: want a valid 8/11-character BIC", ErrInvalidCAMT058Export, opts.ServicingBIC)
	}
	sched, err := l.GetTransferSchedule(opts.ScheduleID)
	if err != nil {
		return "", err
	}
	// The gate is the deliberate opposite of camt.057: only a
	// schedule whose notification premise is dead can be
	// cancelled. An active schedule is revocable only once its
	// next run has passed EndsAt — zero EndsAt means "no end",
	// so such a schedule always still has a live next run.
	if sched.Status == ScheduleActive && (sched.EndsAt.IsZero() || !sched.NextRunAt.After(sched.EndsAt)) {
		return "", fmt.Errorf("%w: schedule %q is still active with a next run at %s", ErrCAMT058ScheduleStillActive, opts.ScheduleID, sched.NextRunAt.UTC().Format(time.RFC3339))
	}
	// MsgId / OrgnlMsgId / OrgnlNtfctnId are all Max35Text: a long
	// schedule ID fails loud here rather than emitting a
	// non-conformant document.
	msgID := camt058MsgID(sched.ID, sched.RunSeq)
	if len(msgID) > 35 {
		return "", fmt.Errorf("%w: message ID %q exceeds Max35Text", ErrInvalidCAMT058Export, msgID)
	}
	origMsgID := camt057MsgID(sched.ID, sched.RunSeq)
	if len(origMsgID) > 35 {
		return "", fmt.Errorf("%w: original message ID %q exceeds Max35Text", ErrInvalidCAMT058Export, origMsgID)
	}
	var cxlRsn *camt058xCxlRsn
	if reason := strings.TrimSpace(opts.Reason); reason != "" {
		cxlRsn = &camt058xCxlRsn{Rsn: camt058xRsn{Prtry: reason}}
	}
	doc := camt058xDocument{
		NtfctnToRcvCxlAdvc: camt058xNtfctnToRcvCxlAdvc{
			GrpHdr: camt058xGrpHdr{MsgID: msgID, CreDtTm: time.Now().UTC().Format(time.RFC3339)},
			OrgnlNtfctn: camt058xOrgnlNtfctn{
				OrgnlMsgId:    origMsgID,
				OrgnlNtfctnId: origMsgID,
			},
			CxlRsn: cxlRsn,
		},
	}
	body, err := xml.MarshalIndent(doc, "", "  ")
	if err != nil {
		return "", fmt.Errorf("%w: %v", ErrInvalidCAMT058Export, err)
	}
	return string(append([]byte(xml.Header), body...)), nil
}
